#!/usr/bin/env python3
"""
img_to_header.py
Pretvaranje slike u C header koji kompajlira bare-metal aplikacija.
Komanda:  python3 img_to_header.py input.jpg test_image.h
Zahtjeva pillow paket  (pip install pillow)
"""
import sys

WIDTH, HEIGHT = 360, 240

def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]

    try:
        from PIL import Image
    except ImportError:
        sys.exit("pillow nedostaje:  pip install pillow")

    im = Image.open(src).convert("L").resize((WIDTH, HEIGHT), Image.BILINEAR)
    data = im.tobytes()
    assert len(data) == WIDTH * HEIGHT

    with open(dst, "w") as f:
        f.write("/* Generated by img_to_header.py from %s */\n" % src)
        f.write("#ifndef TEST_IMAGE_H\n#define TEST_IMAGE_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("#define TEST_IMAGE_WIDTH  %d\n" % WIDTH)
        f.write("#define TEST_IMAGE_HEIGHT %d\n\n" % HEIGHT)
        f.write("static const uint8_t test_image[%d] = {\n" % (WIDTH * HEIGHT))
        for i in range(0, len(data), 16):
            f.write("    " + ",".join("%3d" % b for b in data[i:i+16]) + ",\n")
        f.write("};\n\n#endif\n")

    print("wrote %s  (%d bytes of pixel data)" % (dst, len(data)))

if __name__ == "__main__":
    sys.argv = ["img_to_header.py", "input.jpg", "test_image.h"]
    main()